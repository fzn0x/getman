export type IconName = keyof typeof art;

/** The rectangles of an icon, one per horizontal run of ink. */
export function iconRects(name: IconName): { x: number; y: number; w: number }[] {
  const rects: { x: number; y: number; w: number }[] = [];
  art[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        const start = x;
        while (row[x] === "#") x++;
        rects.push({ x: start, y, w: x - start });
      } else {
        x++;
      }
    }
  });
  return rects;
}
